  email          text not null check (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  phone          text,
  message        text check (char_length(message) <= 3000),
  status         public.inquiry_status not null default 'new',
  created_at     timestamptz not null default now()
);

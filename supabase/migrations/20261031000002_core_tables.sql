  last_sent_at  timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index job_alerts_student_idx on public.job_alerts (student_id);

-- -----------------------------------------------------------------------------
-- Career fairs (Process 8.3)
-- -----------------------------------------------------------------------------
create table public.events (
  id                       uuid primary key default gen_random_uuid(),
  title                    text not null check (char_length(title) between 3 and 200),
  description              text,
  organizer_university_id  uuid references public.universities (id) on delete set null,  -- null = platform event
  starts_at                timestamptz not null,
  ends_at                  timestamptz not null,
  location                 text,
  is_virtual               boolean not null default false,
  capacity                 integer check (capacity > 0),
  status                   public.event_status not null default 'draft',
  cover_path               text,
  created_by               uuid references public.profiles (id) on delete set null,
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),
  check (ends_at > starts_at)
);
create index events_starts_idx on public.events (status, starts_at);

create table public.event_booths (
  id           uuid primary key default gen_random_uuid(),
  event_id     uuid not null references public.events (id) on delete cascade,
  company_id   uuid not null references public.companies (id) on delete cascade,
  status       public.approval_status not null default 'pending',
  booth_label  text,
  note         text,
  reviewed_by  uuid references public.profiles (id) on delete set null,
  created_at   timestamptz not null default now(),
  unique (event_id, company_id)
);

create table public.event_registrations (
  event_id       uuid not null references public.events (id) on delete cascade,
  student_id     uuid not null references public.profiles (id) on delete cascade,
  ticket_code    text not null unique default upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10)),
  checked_in_at  timestamptz,
  created_at     timestamptz not null default now(),
  primary key (event_id, student_id)
);
create index event_registrations_student_idx on public.event_registrations (student_id);

-- -----------------------------------------------------------------------------
-- University portal (Process 8.4)
-- -----------------------------------------------------------------------------
create table public.internship_reports (
  id                 uuid primary key default gen_random_uuid(),
  application_id     uuid not null unique references public.applications (id) on delete cascade,
  student_id         uuid not null references public.profiles (id) on delete cascade,
  university_id      uuid references public.universities (id) on delete set null,
  student_summary    text check (char_length(student_summary) <= 10000),
  employer_rating    smallint check (employer_rating between 1 and 5),
  employer_comment   text check (char_length(employer_comment) <= 5000),
  status             public.cert_status not null default 'draft',
  review_note        text,
  certified_by       uuid references public.profiles (id) on delete set null,
  certified_at       timestamptz,
  verification_code  text unique,       -- printed as a QR code on the certified PDF
  file_path          text,              -- storage: internship-reports/<student_id>/...
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create index internship_reports_university_idx on public.internship_reports (university_id, status);


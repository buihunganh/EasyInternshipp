-- =============================================================================
-- EasyInternshipp — 02: core tables
-- Data stores from DFD Level 1:
--   D1 Users & Profiles  → profiles, student_profiles, university_officers, companies, company_members
--   D2 Jobs              → jobs, job_skills, screening_questions, screening_question_keys
--   D3 Applications      → applications, application_answers, application_status_history, offers
--   D4 CVs               → cvs
--   D5 Messages/Appts    → conversations, conversation_participants, messages, interviews
--   D6 Community         → posts, post_comments, post_likes, post_bookmarks
--   D7 Reports           → reports
--   D8 Admin & Audit     → audit_logs, platform_settings
--   D9 Saved Jobs        → saved_jobs, job_alerts
--   D10 Pipeline/Evals   → pipeline_stages, evaluations
--   Process 8.0          → notifications, events, event_booths, event_registrations,
--                          internship_reports, university_partnerships, partner_inquiries
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Reference data
-- -----------------------------------------------------------------------------
create table public.universities (
  id            uuid primary key default gen_random_uuid(),
  name          text not null unique,
  short_name    text,
  city          text,
  email_domain  text unique,            -- used to auto-link student sign-ups (e.g. hcmut.edu.vn)
  website       text,
  logo_path     text,
  created_at    timestamptz not null default now()
);

create table public.industries (
  id    smallint generated by default as identity primary key,
  slug  text not null unique,
  name  text not null
);

create table public.skills (
  id    integer generated by default as identity primary key,
  name  text not null,
  slug  text not null unique
);

-- -----------------------------------------------------------------------------
-- Users (abstract User → Student / Employer / UniversityOfficer / SystemAdmin)
-- Authentication lives in auth.users (Supabase Auth); passwords are never stored here.
-- -----------------------------------------------------------------------------
create table public.profiles (
  id             uuid primary key references auth.users (id) on delete cascade,
  role           public.user_role not null default 'student',
  status         public.account_status not null default 'active',
  full_name      text not null default '' check (char_length(full_name) <= 120),
  email          text,
  phone          text check (phone is null or phone ~ '^\+?[0-9 ]{8,15}$'),
  avatar_path    text,                  -- storage: avatars/<user_id>/...
  status_reason  text,                  -- reason for suspension / deactivation
  last_seen_at   timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index profiles_role_idx on public.profiles (role);

create table public.student_profiles (
  user_id              uuid primary key references public.profiles (id) on delete cascade,
  university_id        uuid references public.universities (id) on delete set null,
  student_code         text,            -- MSSV
  major                text,
  gpa                  numeric(3, 2) check (gpa between 0 and 4),
  graduation_year      smallint check (graduation_year between 1990 and 2100),
  headline             text check (char_length(headline) <= 160),
  bio                  text check (char_length(bio) <= 3000),
  city                 text,
  links                jsonb not null default '{}'::jsonb,   -- {github, linkedin, portfolio}
  is_looking_for_job   boolean not null default true,
  verification_status  public.verify_status not null default 'unverified',
  verified_by          uuid references public.profiles (id) on delete set null,
  verified_at          timestamptz,
  verification_note    text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  unique (university_id, student_code)
);
create index student_profiles_university_idx on public.student_profiles (university_id);

create table public.student_skills (
  student_id  uuid not null references public.student_profiles (user_id) on delete cascade,
  skill_id    integer not null references public.skills (id) on delete cascade,
  level       smallint check (level between 1 and 5),
  primary key (student_id, skill_id)
);
create index student_skills_skill_idx on public.student_skills (skill_id);

create table public.university_officers (
  user_id        uuid primary key references public.profiles (id) on delete cascade,
  university_id  uuid not null references public.universities (id) on delete cascade,
  officer_code   text,
  department     text,
  title          text,
  created_at     timestamptz not null default now()
);
create index university_officers_university_idx on public.university_officers (university_id);

-- -----------------------------------------------------------------------------
-- Companies (UC-03) and recruiter membership. Employer.companyId from the class
-- diagram becomes a membership table so a company can have a recruiting team.
-- -----------------------------------------------------------------------------
create table public.companies (
  id                   uuid primary key default gen_random_uuid(),
  name                 text not null check (char_length(name) between 2 and 200),
  slug                 text not null unique,
  tax_code             text unique check (tax_code ~ '^[0-9]{10}(-?[0-9]{3})?$'),  -- MST: 10 or 13 digits
  industry_id          smallint references public.industries (id) on delete set null,
  website              text,
  address              text,
  city                 text,
  logo_path            text,            -- storage: company-assets/<company_id>/...
  cover_path           text,
  description          text check (char_length(description) <= 10000),
  company_size         text,
  founded_year         smallint check (founded_year between 1800 and 2100),
  verification_status  public.verify_status not null default 'unverified',  -- "tích xanh"
  verified_at          timestamptz,
  verified_by          uuid references public.profiles (id) on delete set null,
  verification_note    text,
  follower_count       integer not null default 0,
  created_by           uuid references public.profiles (id) on delete set null,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);
create index companies_verification_idx on public.companies (verification_status);

create table public.company_members (
  company_id      uuid not null references public.companies (id) on delete cascade,
  user_id         uuid not null references public.profiles (id) on delete cascade,
  member_role     public.company_member_role not null default 'recruiter',
  position_title  text,
  department      text,
  created_at      timestamptz not null default now(),
  primary key (company_id, user_id)
);
create index company_members_user_idx on public.company_members (user_id);

-- Business licence (GPKD) / tax documents submitted for verification
create table public.company_documents (
  id            uuid primary key default gen_random_uuid(),
  company_id    uuid not null references public.companies (id) on delete cascade,
  doc_type      text not null check (doc_type in ('business_license', 'tax_certificate', 'authorization_letter', 'other')),
  file_path     text not null,          -- storage: company-documents/<company_id>/...
  status        public.verify_status not null default 'pending',
  submitted_by  uuid references public.profiles (id) on delete set null,
  reviewed_by   uuid references public.profiles (id) on delete set null,
  review_note   text,
  created_at    timestamptz not null default now(),
  reviewed_at   timestamptz
);
create index company_documents_company_idx on public.company_documents (company_id);

create table public.company_follows (
  student_id  uuid not null references public.profiles (id) on delete cascade,
  company_id  uuid not null references public.companies (id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (student_id, company_id)
);
create index company_follows_company_idx on public.company_follows (company_id);

-- University ↔ company cooperation agreements (MoU)
create table public.university_partnerships (
  id             uuid primary key default gen_random_uuid(),
  university_id  uuid not null references public.universities (id) on delete cascade,
  company_id     uuid not null references public.companies (id) on delete cascade,
  status         public.partnership_status not null default 'pending',
  starts_on      date,
  ends_on        date,
  document_path  text,
  note           text,
  created_by     uuid references public.profiles (id) on delete set null,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  unique (university_id, company_id),
  check (ends_on is null or starts_on is null or ends_on >= starts_on)
);

-- -----------------------------------------------------------------------------
-- CVs (D4)
-- -----------------------------------------------------------------------------
create table public.cvs (
  id           uuid primary key default gen_random_uuid(),
  student_id   uuid not null references public.profiles (id) on delete cascade,
  title        text not null default 'CV của tôi' check (char_length(title) <= 120),
  source       public.cv_source not null default 'builder',
  template     text not null default 'modern',
  content      jsonb not null default '{}'::jsonb,   -- CV Builder data: education, projects, skills...
  file_path    text,                                 -- storage: cvs/<student_id>/... (upload or generated PDF)
  is_default   boolean not null default false,
  is_public    boolean not null default false,
  public_slug  text unique,                          -- shareable public link
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  check (source = 'builder' or file_path is not null),
  check (not is_public or public_slug is not null)
);
create index cvs_student_idx on public.cvs (student_id);
create unique index cvs_one_default_per_student on public.cvs (student_id) where is_default;

-- -----------------------------------------------------------------------------
-- Jobs (D2)
-- -----------------------------------------------------------------------------
create table public.jobs (
  id                   uuid primary key default gen_random_uuid(),
  company_id           uuid not null references public.companies (id) on delete cascade,
  created_by           uuid references public.profiles (id) on delete set null,
  title                text not null check (char_length(title) between 3 and 200),
  description          text not null default '' check (char_length(description) <= 20000),
  requirements         text not null default '' check (char_length(requirements) <= 10000),
  benefits             text not null default '' check (char_length(benefits) <= 10000),
  industry_id          smallint references public.industries (id) on delete set null,
  city                 text,
  address              text,
  work_type            public.work_type not null default 'onsite',
  schedule             public.work_schedule not null default 'full_time',
  duration_months      smallint check (duration_months between 1 and 24),
  openings             smallint not null default 1 check (openings > 0),
  stipend_min          integer check (stipend_min >= 0),       -- monthly allowance (phụ cấp)
  stipend_max          integer check (stipend_max >= 0),
  stipend_currency     char(3) not null default 'VND',
  stipend_negotiable   boolean not null default false,
  deadline             timestamptz,
  status               public.job_status not null default 'draft',
  rejection_reason     text,
  -- University-exclusive (MoU) postings: only verified students of that university see them
  university_id        uuid references public.universities (id) on delete set null,
  university_approval  public.approval_status,
  university_note      text,
  submitted_at         timestamptz,
  published_at         timestamptz,
  closed_at            timestamptz,
  view_count           integer not null default 0,
  application_count    integer not null default 0,
  search               tsvector generated always as (
                         setweight(to_tsvector('simple'::regconfig, private.unaccent_immutable(coalesce(title, ''))), 'A') ||
                         setweight(to_tsvector('simple'::regconfig, private.unaccent_immutable(coalesce(city, ''))), 'B') ||
                         setweight(to_tsvector('simple'::regconfig, private.unaccent_immutable(coalesce(requirements, ''))), 'C') ||
                         setweight(to_tsvector('simple'::regconfig, private.unaccent_immutable(coalesce(description, ''))), 'D')
                       ) stored,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  check (stipend_max is null or stipend_min is null or stipend_max >= stipend_min),
  check ((university_id is null) = (university_approval is null))
);
create index jobs_company_idx on public.jobs (company_id);
create index jobs_status_published_idx on public.jobs (status, published_at desc);
create index jobs_deadline_idx on public.jobs (deadline) where status = 'active';
create index jobs_search_idx on public.jobs using gin (search);
create index jobs_title_trgm_idx on public.jobs using gin (title extensions.gin_trgm_ops);

create table public.job_skills (
  job_id       uuid not null references public.jobs (id) on delete cascade,
  skill_id     integer not null references public.skills (id) on delete cascade,
  is_required  boolean not null default true,
  primary key (job_id, skill_id)
);
create index job_skills_skill_idx on public.job_skills (skill_id);

-- Knockout / screening questions (ScreeningQuestion)
create table public.screening_questions (
  id           uuid primary key default gen_random_uuid(),
  job_id       uuid not null references public.jobs (id) on delete cascade,
  position     smallint not null default 0,
  question     text not null check (char_length(question) between 3 and 500),
  kind         public.question_kind not null default 'yes_no',
  options      jsonb not null default '[]'::jsonb,     -- choices for single_choice
  is_required  boolean not null default true,
  is_knockout  boolean not null default false,
  created_at   timestamptz not null default now()
);
create index screening_questions_job_idx on public.screening_questions (job_id, position);

-- Ideal answers live apart so candidates can read questions but never the answer key
create table public.screening_question_keys (
  question_id   uuid primary key references public.screening_questions (id) on delete cascade,
  ideal_answer  text not null
);

create table public.saved_jobs (
  student_id  uuid not null references public.profiles (id) on delete cascade,
  job_id      uuid not null references public.jobs (id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (student_id, job_id)
);
create index saved_jobs_job_idx on public.saved_jobs (job_id);

-- Raw view events (feeds jobs.view_count and the warehouse)
create table public.job_views (
  id         bigint generated always as identity primary key,
  job_id     uuid not null references public.jobs (id) on delete cascade,
  viewer_id  uuid references public.profiles (id) on delete set null,
  viewed_at  timestamptz not null default now()
);
create index job_views_job_time_idx on public.job_views (job_id, viewed_at);

-- -----------------------------------------------------------------------------
-- ATS: pipeline, applications, interviews, evaluations, offers (D3, D10)
-- -----------------------------------------------------------------------------
-- Kanban columns per job (renamable, like the "Cấu hình quy trình" feature).
-- Organisational only; the lifecycle lives in applications.status.
create table public.pipeline_stages (
  id          uuid primary key default gen_random_uuid(),
  job_id      uuid not null references public.jobs (id) on delete cascade,
  name        text not null check (char_length(name) between 1 and 60),
  position    smallint not null default 0,
  created_at  timestamptz not null default now()
);
create index pipeline_stages_job_idx on public.pipeline_stages (job_id, position);

create table public.applications (
  id                 uuid primary key default gen_random_uuid(),
  job_id             uuid not null references public.jobs (id) on delete cascade,
  student_id         uuid not null references public.profiles (id) on delete cascade,
  cv_id              uuid references public.cvs (id) on delete set null,
  cv_snapshot        jsonb,             -- CV content frozen at submission time
  cv_file_path       text,              -- CV file frozen at submission time
  cover_letter       text check (char_length(cover_letter) <= 5000),
  status             public.application_status not null default 'applied',
  stage_id           uuid references public.pipeline_stages (id) on delete set null,
  score              smallint check (score between 0 and 100),   -- average of evaluations
  knockout_passed    boolean,
  rejection_reason   text,
  withdrawal_reason  text,
  applied_at         timestamptz not null default now(),
  viewed_at          timestamptz,       -- "NTD đã xem CV" signal
  status_changed_at  timestamptz not null default now(),
  hired_at           timestamptz,
  updated_at         timestamptz not null default now(),
  unique (job_id, student_id)           -- one application per job (anti-duplicate rule)
);
create index applications_student_idx on public.applications (student_id, applied_at desc);
create index applications_job_status_idx on public.applications (job_id, status);
create index applications_stage_idx on public.applications (stage_id);

create table public.application_answers (
  application_id  uuid not null references public.applications (id) on delete cascade,
  question_id     uuid not null references public.screening_questions (id) on delete cascade,
  answer          text not null check (char_length(answer) <= 2000),
  passed          boolean,
  primary key (application_id, question_id)
);

create table public.application_status_history (
  id              bigint generated always as identity primary key,
  application_id  uuid not null references public.applications (id) on delete cascade,
  from_status     public.application_status,
  to_status       public.application_status not null,
  changed_by      uuid references public.profiles (id) on delete set null,
  note            text,
  changed_at      timestamptz not null default now()
);
create index application_status_history_app_idx on public.application_status_history (application_id, changed_at);

create table public.interviews (
  id                uuid primary key default gen_random_uuid(),
  application_id    uuid not null references public.applications (id) on delete cascade,
  round             smallint not null default 1 check (round between 1 and 20),
  scheduled_at      timestamptz not null,
  duration_minutes  smallint not null default 45 check (duration_minutes between 10 and 480),
  mode              public.interview_mode not null default 'online',
  meeting_url       text,
  location          text,
  status            public.interview_status not null default 'scheduled',
  rsvp              public.rsvp_status not null default 'pending',
  rsvp_note         text,
  proposed_at       timestamptz,        -- candidate's proposed new time when rescheduling
  created_by        uuid references public.profiles (id) on delete set null,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
create index interviews_application_idx on public.interviews (application_id);
create index interviews_scheduled_idx on public.interviews (scheduled_at) where status = 'scheduled';

-- Scorecards (0–100)
create table public.evaluations (
  id              uuid primary key default gen_random_uuid(),
  application_id  uuid not null references public.applications (id) on delete cascade,
  interview_id    uuid references public.interviews (id) on delete set null,
  evaluator_id    uuid references public.profiles (id) on delete set null,
  score           smallint not null check (score between 0 and 100),
  criteria        jsonb not null default '{}'::jsonb,   -- e.g. {"technical": 90, "communication": 80}
  comment         text check (char_length(comment) <= 5000),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index evaluations_application_idx on public.evaluations (application_id);

-- Digital offers (JobOffer)
create table public.offers (
  id              uuid primary key default gen_random_uuid(),
  application_id  uuid not null references public.applications (id) on delete cascade,
  stipend_amount  integer check (stipend_amount >= 0),
  currency        char(3) not null default 'VND',
  start_date      date not null,
  end_date        date,
  expires_at      timestamptz not null,
  terms           text check (char_length(terms) <= 10000),
  letter_path     text,                 -- storage: offer-letters/<application_id>/...
  status          public.offer_status not null default 'sent',
  response_note   text,
  created_by      uuid references public.profiles (id) on delete set null,
  sent_at         timestamptz not null default now(),
  responded_at    timestamptz,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  check (end_date is null or end_date > start_date)
);
create index offers_application_idx on public.offers (application_id);
create unique index offers_one_open_per_application on public.offers (application_id) where status in ('sent', 'accepted');

-- -----------------------------------------------------------------------------
-- Messaging (D5)
-- -----------------------------------------------------------------------------
create table public.conversations (
  id                    uuid primary key default gen_random_uuid(),
  company_id            uuid references public.companies (id) on delete cascade,
  application_id        uuid references public.applications (id) on delete set null,
  created_by            uuid references public.profiles (id) on delete set null,
  last_message_at       timestamptz,
  last_message_preview  text,
  created_at            timestamptz not null default now()
);
create index conversations_last_message_idx on public.conversations (last_message_at desc);

create table public.conversation_participants (
  conversation_id  uuid not null references public.conversations (id) on delete cascade,
  user_id          uuid not null references public.profiles (id) on delete cascade,
  last_read_at     timestamptz,
  is_muted         boolean not null default false,
  is_archived      boolean not null default false,
  joined_at        timestamptz not null default now(),
  primary key (conversation_id, user_id)
);
create index conversation_participants_user_idx on public.conversation_participants (user_id);

create table public.messages (
  id               uuid primary key default gen_random_uuid(),
  conversation_id  uuid not null references public.conversations (id) on delete cascade,
  sender_id        uuid references public.profiles (id) on delete set null,
  kind             public.message_kind not null default 'text',
  body             text check (char_length(body) <= 5000),
  attachment_path  text,                -- storage: message-attachments/<conversation_id>/...
  attachment_name  text,
  attachment_size  integer,
  metadata         jsonb not null default '{}'::jsonb,   -- e.g. interview invite card
  created_at       timestamptz not null default now(),
  edited_at        timestamptz,
  deleted_at       timestamptz,
  check (kind <> 'text' or body is not null),
  check (kind <> 'file' or attachment_path is not null)
);
create index messages_conversation_time_idx on public.messages (conversation_id, created_at desc);

-- -----------------------------------------------------------------------------
-- Community forum (D6): experience posts, anonymous Q&A, company reviews, documents
-- -----------------------------------------------------------------------------
create table public.posts (
  id               uuid primary key default gen_random_uuid(),
  author_id        uuid not null references public.profiles (id) on delete cascade,
  type             public.post_type not null default 'experience',
  title            text check (char_length(title) <= 200),
  body             text not null check (char_length(body) between 1 and 20000),
  is_anonymous     boolean not null default false,
  company_id       uuid references public.companies (id) on delete set null,
  rating           smallint check (rating between 1 and 5),
  tags             text[] not null default '{}',
  attachment_path  text,                -- storage: post-attachments/<user_id>/...
  status           public.content_status not null default 'published',
  like_count       integer not null default 0,
  comment_count    integer not null default 0,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  check (type = 'review' or rating is null),
  check (type <> 'review' or (company_id is not null and rating is not null))
);
create index posts_feed_idx on public.posts (status, created_at desc);
create index posts_company_idx on public.posts (company_id) where company_id is not null;
create index posts_author_idx on public.posts (author_id);
create index posts_tags_idx on public.posts using gin (tags);

create table public.post_comments (
  id            uuid primary key default gen_random_uuid(),
  post_id       uuid not null references public.posts (id) on delete cascade,
  author_id     uuid not null references public.profiles (id) on delete cascade,
  parent_id     uuid references public.post_comments (id) on delete cascade,
  body          text not null check (char_length(body) between 1 and 5000),
  is_anonymous  boolean not null default false,
  status        public.content_status not null default 'published',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index post_comments_post_idx on public.post_comments (post_id, created_at);

create table public.post_likes (
  post_id     uuid not null references public.posts (id) on delete cascade,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (post_id, user_id)
);
create index post_likes_user_idx on public.post_likes (user_id);

create table public.post_bookmarks (
  post_id     uuid not null references public.posts (id) on delete cascade,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (post_id, user_id)
);
create index post_bookmarks_user_idx on public.post_bookmarks (user_id);

